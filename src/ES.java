import java.util.*;

public class ES {

    private static Scanner sc = new Scanner(System.in);

    public static int leerInt() {
        return sc.nextInt();
    }

    public static String leerString() {
        return sc.nextLine();
    }

    public static short leerShort() {
        return sc.nextShort();
    }

    public static void cerrarTeclado() {
        sc.close();
    }
}
